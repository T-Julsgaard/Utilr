'use strict';
// Builds the browser version of notr's note for the website's try-it demo.
//   npm run web      (= node scripts/build-web.js)
// Copies the real note UI from tools/notr/ into docs/notr/app/ (so the demo
// always runs the same code as the app), adds the web bridge, and bundles
// the fonts (latin subsets only) next to it. docs/notr/app/bridge.js and
// web.css are hand-written and stay as they are; docs/notr/desk.js plays the
// part of tools/notr/main.js.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = path.join(root, 'tools', 'notr');
const out = path.join(root, 'docs', 'notr', 'app');
const fontsOut = path.join(out, 'fonts');

fs.rmSync(fontsOut, { recursive: true, force: true });
fs.mkdirSync(fontsOut, { recursive: true });

// 1. the note UI, unchanged
for (const f of ['note.css', 'themes.css', 'shortcuts.js', 'note.js']) {
  fs.copyFileSync(path.join(src, f), path.join(out, f));
}

// 2. note.html + the bridge that stands in for Electron's preload
let html = fs.readFileSync(path.join(src, 'note.html'), 'utf8');
html = html
  .replace('<link rel="stylesheet" href="themes.css">',
    '<link rel="stylesheet" href="themes.css">\n<link rel="stylesheet" href="web.css">')
  .replace('<script src="shortcuts.js"></script>',
    '<script src="bridge.js"></script>\n  <script src="shortcuts.js"></script>');
if (!html.includes('bridge.js') || !html.includes('web.css')) throw new Error('note.html changed: update build-web.js');
fs.writeFileSync(path.join(out, 'note.html'), '<!-- generated by scripts/build-web.js from tools/notr/note.html -->\n' + html);

// 3. fonts: the same files the tool bundles, latin + latin-ext only
const fontDir = path.join(src, 'fonts');
const text = fs.readFileSync(path.join(fontDir, 'fonts.css'), 'utf8');
let css = '/* generated by scripts/build-web.js from tools/notr/fonts (latin subsets) */\n';
let count = 0;
for (const block of text.match(/\/\*[^*]*\*\/\s*@font-face\s*\{[^}]*\}/g) || []) {
  const name = block.match(/\/\*\s*([^*]+?)\s*\*\//)[1];
  if (!/-latin-(ext-)?\d+-(normal|italic)$/.test(name)) continue;
  const woff2 = block.match(/url\(files\/([^)]+\.woff2)\)/)[1];
  fs.copyFileSync(path.join(fontDir, 'files', woff2), path.join(fontsOut, woff2));
  css += block.replace(/src:[^;]+;/, `src: url(fonts/${woff2}) format('woff2');`) + '\n\n';
  count++;
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);
fs.copyFileSync(path.join(fontDir, 'OFL.txt'), path.join(fontsOut, 'OFL.txt'));

console.log(`docs/notr/app built: note UI + ${count} font files`);
