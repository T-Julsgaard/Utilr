'use strict';
// Builds the browser version of the note for the GitHub Pages demo.
//   node scripts/build-web.js
// Copies the real note UI from src/ into docs/app/ (so the demo always runs
// the same code as the desktop app), adds the web bridge, and bundles the
// fonts (latin subsets only, woff2) next to it.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = path.join(root, 'src');
const out = path.join(root, 'docs', 'app');
const fontsOut = path.join(out, 'fonts');

fs.mkdirSync(fontsOut, { recursive: true });

// 1. the note UI, unchanged
for (const f of ['note.css', 'themes.css', 'shortcuts.js', 'note.js']) {
  fs.copyFileSync(path.join(src, f), path.join(out, f));
}

// 2. note.html + the bridge that stands in for Electron's preload
let html = fs.readFileSync(path.join(src, 'note.html'), 'utf8');
html = html
  .replace('<link rel="stylesheet" href="themes.css">',
    '<link rel="stylesheet" href="themes.css">\n<link rel="stylesheet" href="web.css">')
  .replace('<script src="shortcuts.js"></script>',
    '<script src="bridge.js"></script>\n  <script src="shortcuts.js"></script>');
if (!html.includes('bridge.js') || !html.includes('web.css')) throw new Error('note.html changed: update build-web.js');
fs.writeFileSync(path.join(out, 'note.html'), '<!-- generated by scripts/build-web.js from src/note.html -->\n' + html);

// 3. fonts: read the same @fontsource files the app uses, keep latin + latin-ext
const imports = fs.readFileSync(path.join(src, 'fonts.css'), 'utf8')
  .match(/@import url\("([^"]+)"\)/g)
  .map((s) => s.match(/"([^"]+)"/)[1]);

let css = '/* generated by scripts/build-web.js from src/fonts.css (latin subsets) */\n';
let count = 0;
for (const rel of imports) {
  const file = path.resolve(src, rel);
  const dir = path.dirname(file);
  const text = fs.readFileSync(file, 'utf8');
  for (const block of text.match(/\/\*[^*]*\*\/\s*@font-face\s*\{[^}]*\}/g) || []) {
    const name = block.match(/\/\*\s*([^*]+?)\s*\*\//)[1];
    if (!/-latin-(ext-)?\d+-(normal|italic)$/.test(name)) continue;
    const woff2 = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)[1];
    fs.copyFileSync(path.join(dir, 'files', woff2), path.join(fontsOut, woff2));
    css += block
      .replace(/src:[^;]+;/, `src: url(fonts/${woff2}) format('woff2');`) + '\n\n';
    count++;
  }
}
fs.writeFileSync(path.join(out, 'fonts.css'), css);

console.log(`docs/app built: note UI + ${count} font files`);
